# Program 1: Create numeric, character, and logical vectors and display type and content.

# Numeric vector
num_vec <- c(10, 20.5, 30, 40.75, 50)
print(num_vec)
print(class(num_vec))

# Character vector
char_vec <- c("Anu", "Bala", "Charan", "Divya")
print(char_vec)
print(class(char_vec))

# Logical vector
log_vec <- c(TRUE, FALSE, TRUE, FALSE)
print(log_vec)
print(class(log_vec))
