# Program 22: If-Else and Arithmetic & Boolean Operators

num <- 5
if (num > 0) {
  result <- "Positive"
} else if (num < 0) {
  result <- "Negative"
} else {
  result <- "Zero"
}

a <- 10
b <- 3
sum_val <- a + b
diff_val <- a - b
prod_val <- a * b
div_val <- a / b
bool1 <- (a > b)
bool2 <- (a == b)
bool3 <- (a != b)

print(result)
print(sum_val)
print(diff_val)
print(prod_val)
print(div_val)
print(bool1)
print(bool2)
print(bool3)
